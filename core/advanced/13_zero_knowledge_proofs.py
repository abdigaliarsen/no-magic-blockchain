# Group order — number of points generated by G
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141

# Identity point (point at infinity)
IDENTITY = None

# Prime for R1CS finite field arithmetic (a 128-bit prime for manageable demo)
R1CS_PRIME = 2**127 - 1  # Mersenne prime, large enough for our circuits

