# Part 2: Simplified R1CS (Rank-1 Constraint System)
# ----------------------------------------------------------------------------
# R1CS encodes arithmetic circuits as a system of constraints of the form:
#     (a · w) * (b · w) = (c · w)
# where w is the "witness" vector and a, b, c are coefficient vectors.
#
# Example: proving x*x + x = 42 (i.e., x² + x - 42 = 0, solution x=6)
# We flatten this into:
#   Gate 1: v1 = x * x         →  a=[0,1,0], b=[0,1,0], c=[0,0,1]
#   Gate 2: out = v1 + x       →  a=[0,1,1], b=[1,0,0], c=[42,0,0]
# Witness: w = [1, x, v1]  (where index 0 is the constant "1")

FP = R1CS_PRIME  # Shorthand for the field prime


def fp_mod(x: int) -> int:
    """Reduce x modulo the field prime."""
    return x % FP


def dot_product(a: list[int], b: list[int]) -> int:
    """Compute dot product of two vectors over GF(FP)."""
    result = 0
    for ai, bi in zip(a, b):
        result = (result + ai * bi) % FP
    return result


class R1CSCircuit:
    """A simple R1CS circuit with constraints of the form (a·w)*(b·w) = (c·w).

    Each constraint is a "gate" in the arithmetic circuit. The circuit is
    satisfiable if there exists a witness w that makes all constraints hold.
    """

    def __init__(self):
        self.constraints = []  # List of (a, b, c) tuples
        self.num_vars = 0      # Number of variables (including constant 1)

    def add_constraint(self, a: list[int], b: list[int], c: list[int]):
        """Add a constraint: (a·w) * (b·w) = (c·w)."""
        self.constraints.append((a, b, c))
        # Track the number of variables from the longest vector
        self.num_vars = max(self.num_vars, len(a), len(b), len(c))

    def is_satisfied(self, witness: list[int]) -> tuple[bool, list[bool]]:
        """Check if the witness satisfies all constraints.

        Returns (all_satisfied, per_constraint_results).
        """
        results = []
        for a, b, c in self.constraints:
            # Pad vectors to witness length if needed
            a_padded = a + [0] * (len(witness) - len(a))
            b_padded = b + [0] * (len(witness) - len(b))
            c_padded = c + [0] * (len(witness) - len(c))

            # Compute (a·w) * (b·w) and compare to (c·w)
            left = dot_product(a_padded, witness)
            right = dot_product(b_padded, witness)
            out = dot_product(c_padded, witness)

            product = (left * right) % FP
            results.append(product == out)

        return (all(results), results)


def build_quadratic_circuit() -> tuple[R1CSCircuit, int]:
    """Build an R1CS circuit for: x² + x = 42 (solution: x = 6).

    Flattening into rank-1 constraints:
      Witness vector: w = [1, x, v1]
        Index 0: constant 1 (always present in R1CS)
        Index 1: x (the secret input)
        Index 2: v1 = x * x (intermediate variable)

      Gate 1: v1 = x * x
        a = [0, 1, 0]  →  a·w = x
        b = [0, 1, 0]  →  b·w = x
        c = [0, 0, 1]  →  c·w = v1
        Check: x * x = v1

      Gate 2: v1 + x = 42
        Rewrite as: (v1 + x) * 1 = 42
        a = [0, 1, 1]  →  a·w = x + v1
        b = [1, 0, 0]  →  b·w = 1
        c = [42, 0, 0] →  c·w = 42
        Check: (v1 + x) * 1 = 42
    """
    circuit = R1CSCircuit()

    # Gate 1: x * x = v1
    circuit.add_constraint(
        a=[0, 1, 0],  # selects x
        b=[0, 1, 0],  # selects x
        c=[0, 0, 1],  # selects v1
    )

    # Gate 2: (v1 + x) * 1 = 42
    circuit.add_constraint(
        a=[0, 1, 1],  # selects x + v1
        b=[1, 0, 0],  # selects constant 1
        c=[42, 0, 0], # selects 42 (= 42 * 1)
    )

    # The answer is x=6: 6*6 + 6 = 42
    answer = 6
    return circuit, answer


def build_witness(x: int) -> list[int]:
    """Build a witness vector for the quadratic circuit given input x.

    Witness: [1, x, x*x]
    The prover computes all intermediate values honestly.
    """
    v1 = fp_mod(x * x)  # Intermediate: v1 = x²
    return [1, fp_mod(x), v1]


