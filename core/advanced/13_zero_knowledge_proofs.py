def mod_inverse(a: int, m: int) -> int:
    """Modular inverse via Fermat's little theorem: a^(m-2) mod m."""
    return pow(a, m - 2, m)


def point_add(p1: tuple | None, p2: tuple | None) -> tuple | None:
    """Add two points on secp256k1. Returns None for identity."""
    if p1 is IDENTITY:
        return p2
    if p2 is IDENTITY:
        return p1

    x1, y1 = p1
    x2, y2 = p2

    if x1 == x2 and y1 != y2:  # Inverse points → identity
        return IDENTITY

    if x1 == x2 and y1 == y2:  # Same point → use doubling
        return point_double(p1)

    # Slope through two distinct points
    s = ((y2 - y1) * mod_inverse(x2 - x1, P)) % P
    x3 = (s * s - x1 - x2) % P
    y3 = (s * (x1 - x3) - y1) % P
    return (x3, y3)


def point_double(point: tuple | None) -> tuple | None:
    """Double a point (tangent line intersection)."""
    if point is IDENTITY:
        return IDENTITY
    x, y = point
    if y == 0:
        return IDENTITY
    # Tangent slope: (3x² + A) / (2y), A=0 for secp256k1
    s = ((3 * x * x + A) * mod_inverse(2 * y, P)) % P
    x3 = (s * s - 2 * x) % P
    y3 = (s * (x - x3) - y) % P
    return (x3, y3)


def scalar_multiply(k: int, point: tuple | None) -> tuple | None:
    """Multiply point by scalar using double-and-add (O(log k) steps)."""
    if k == 0 or point is IDENTITY:
        return IDENTITY
    k = k % N
    result = IDENTITY
    addend = point
    while k > 0:
        if k & 1:
            result = point_add(result, addend)
        addend = point_double(addend)
        k >>= 1
    return result


# ----------------------------------------------------------------------------
# Part 1: Schnorr Sigma Protocol
# ----------------------------------------------------------------------------
# The Schnorr protocol proves knowledge of x such that X = x*G,
# without revealing x. It's a 3-step interactive protocol:
#   1. Prover commits: pick random r, send R = r*G
#   2. Verifier challenges: send random c
#   3. Prover responds: send s = r + c*x (mod N)
# Verifier checks: s*G == R + c*X
# Why it works: if s*G = (r + c*x)*G = r*G + c*x*G = R + c*X

class SchnorrProver:
    """Prover who knows secret x and wants to prove knowledge of it."""

    def __init__(self, secret: int):
        self.x = secret  # The secret discrete log
        self.X = scalar_multiply(secret, G)  # Public key X = x*G
        self._r = None  # Nonce, stored between commit and respond steps

    def commit(self) -> tuple:
        """Step 1: Pick random nonce r, return commitment R = r*G.

        The randomness r is critical — reusing it would leak the secret,
        just like nonce reuse in ECDSA (the PS3 hack).
        """
        self._r = random.SystemRandom().randint(1, N - 1)
        R = scalar_multiply(self._r, G)  # Commitment point
        return R

    def respond(self, challenge: int) -> int:
        """Step 3: Compute response s = r + c*x (mod N).

        This cleverly combines the nonce and secret so that the verifier
        can check the relationship without learning either value.
        """
        s = (self._r + challenge * self.x) % N
        self._r = None  # Clear nonce to prevent reuse
        return s


class SchnorrVerifier:
    """Verifier who checks the proof without learning the secret."""

    def __init__(self, public_key: tuple):
        self.X = public_key  # The public key X = x*G

    def challenge(self) -> int:
        """Step 2: Generate a random challenge c.

        The challenge must be unpredictable — if the prover could predict it,
        they could fake a proof without knowing x.
        """
        return random.SystemRandom().randint(1, N - 1)

    def verify(self, R: tuple, c: int, s: int) -> bool:
        """Check: s*G == R + c*X.

        If s = r + c*x, then:
            s*G = (r + c*x)*G = r*G + c*(x*G) = R + c*X
        A cheater who doesn't know x cannot produce a valid s for a random c.
        """
        lhs = scalar_multiply(s, G)        # s*G
        cX = scalar_multiply(c, self.X)     # c*X
        rhs = point_add(R, cX)             # R + c*X
        return lhs == rhs


def run_schnorr_protocol(secret: int) -> dict:
    """Run the full 3-step Schnorr protocol and return all values."""
    prover = SchnorrProver(secret)
    verifier = SchnorrVerifier(prover.X)

    # Step 1: Prover commits
    R = prover.commit()

    # Step 2: Verifier sends challenge
    c = verifier.challenge()

    # Step 3: Prover responds
    s = prover.respond(c)

    # Verification
    valid = verifier.verify(R, c, s)

    return {
        "public_key": prover.X,
        "R": R,
        "challenge": c,
        "response": s,
        "valid": valid,
    }


