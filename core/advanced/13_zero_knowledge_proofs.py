def _hex_short(n: int, length: int = 16) -> str:
    """Format a large integer as a short hex string."""
    h = f"{n:064x}"
    if len(h) > length:
        return f"0x{h[:length//2]}...{h[-length//2:]}"
    return f"0x{h}"


