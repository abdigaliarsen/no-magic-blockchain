def _fmt_hex(data: bytes, n: int = 16) -> str:
    """Format bytes as truncated hex string."""
    h = data.hex()
    if len(h) > n:
        return f"0x{h[:n//2]}...{h[-n//2:]}"
    return f"0x{h}"


def _fmt_point(point: tuple | None) -> str:
    """Format an EC point for display."""
    if point is IDENTITY:
        return "(infinity)"
    x, y = point
    return f"(0x{x:064x}"[:22] + f"..., 0x{y:064x}"[:22] + "...)"


def demo():
    """Run a visual demonstration of Verifiable Random Functions."""

    print("=" * 70)
    print("  Verifiable Random Functions (VRFs)")
    print("=" * 70)

    # --- Key generation ---
    print("\n--- Step 1: Key Generation ---\n")

    sk, pk = VRF.keygen()
    print(f"  Secret key (sk): 0x{sk:064x}"[:42] + "...")
    print(f"  Public key (pk): {_fmt_point(pk)}")

    # --- VRF evaluation ---
    print("\n--- Step 2: VRF Evaluation ---\n")

    input_data = b"block_height:12345"
    print(f'  Input: "{input_data.decode()}"')

    output, gamma, h_point, s, c = VRF.prove(sk, input_data)

    print(f"\n  VRF Output:  {_fmt_hex(output)}")
    print(f"  Gamma point: {_fmt_point(gamma)}")
    print(f"  H(input):    {_fmt_point(h_point)}")
    print(f"  Proof s:     0x{s:064x}"[:42] + "...")
    print(f"  Proof c:     0x{c:064x}"[:42] + "...")

    # --- Verification ---
    print("\n--- Step 3: Verification (anyone with pk can do this) ---\n")

    valid = VRF.verify(pk, input_data, output, gamma, s, c)
    print(f"  Verify(pk, input, output, proof) = {valid}")
    if valid:
        print("  -> Proof is VALID: output was correctly computed by sk holder")

    # --- Determinism: same input always produces same output ---
    print("\n--- Step 4: Determinism ---\n")

    output2, gamma2, _, _, _ = VRF.prove(sk, input_data)
    print(f'  First  prove("{input_data.decode()}"): {_fmt_hex(output)}')
    print(f'  Second prove("{input_data.decode()}"): {_fmt_hex(output2)}')
    print(f"  Outputs match: {output == output2}")
    print("  -> Same sk + same input = same output (deterministic)")

    # --- Different inputs produce different outputs ---
    print("\n--- Step 5: Different Inputs -> Different Outputs ---\n")

    inputs = [b"slot:100", b"slot:101", b"slot:102"]
    print("  Input                Output")
    print("  " + "-" * 55)
    for inp in inputs:
        out, _, _, _, _ = VRF.prove(sk, inp)
        print(f'  "{inp.decode()}"' + " " * (20 - len(inp)) + f"  {_fmt_hex(out)}")
    print()
    print("  -> Each input maps to a unique, unpredictable output")

    # --- Tamper detection ---
    print("\n--- Step 6: Tamper Detection ---\n")

    # Try to verify with wrong input
    wrong_input = b"block_height:99999"
    valid_wrong = VRF.verify(pk, wrong_input, output, gamma, s, c)
    print(f"  Verify with wrong input:  {valid_wrong}")

    # Try to verify with tampered output
    tampered_output = bytes([output[0] ^ 0xFF]) + output[1:]
    valid_tampered = VRF.verify(pk, input_data, tampered_output, gamma, s, c)
    print(f"  Verify with tampered output: {valid_tampered}")

    # Try to verify with wrong public key
    _, wrong_pk = VRF.keygen()
    valid_wrong_pk = VRF.verify(wrong_pk, input_data, output, gamma, s, c)
    print(f"  Verify with wrong pk:     {valid_wrong_pk}")

    print("\n  -> All tampered/mismatched verifications correctly FAIL")

    # --- How it works ---
    print("\n--- How VRFs Work ---\n")
    print("  ┌────────────────────────────────────────────────────────┐")
    print("  │  PROVER (has secret key sk):                          │")
    print("  │    1. H = hash_to_curve(input)                        │")
    print("  │    2. gamma = sk * H          (VRF core)              │")
    print("  │    3. output = SHA256(gamma)   (pseudorandom output)  │")
    print("  │    4. proof = DLEQ(sk, G, H)  (proves sk was used)   │")
    print("  │                                                       │")
    print("  │  VERIFIER (has public key pk = sk * G):               │")
    print("  │    1. Check DLEQ proof         (no sk needed)         │")
    print("  │    2. Check output = SHA256(gamma)                    │")
    print("  │    3. If both pass -> output is authentic             │")
    print("  └────────────────────────────────────────────────────────┘")

    # --- Blockchain application ---
    print("\n--- Blockchain Application: Leader Selection ---\n")
    print("  In Algorand/Cardano, each validator runs VRF with their sk")
    print("  and the current slot number as input. If the VRF output")
    print("  (interpreted as a number) falls below a threshold, that")
    print("  validator is selected as the block proposer. The proof")
    print("  lets everyone verify the selection was fair.")

    print()
    print("=" * 70)
    print("  VRF demonstration complete.")
    print("=" * 70)


