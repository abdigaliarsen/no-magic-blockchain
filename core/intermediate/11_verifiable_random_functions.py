"""
TITLE: Verifiable Random Functions (VRFs)
CATEGORY: core

WHAT THIS IMPLEMENTS:
    A simplified Verifiable Random Function (VRF) using elliptic curve
    cryptography on secp256k1. A VRF lets a secret key holder produce a
    pseudorandom output for any input, along with a proof that the output
    was correctly computed — anyone with the public key can verify the proof
    without learning the secret key.

KEY CONCEPTS:
    - Deterministic pseudorandom output from secret key + input
    - Non-interactive proof of correct computation
    - EC-based hash-to-curve mapping
    - Verifiability: anyone can check output matches the proof

PREREQUISITE SCRIPTS:
    - core/fundamentals/02_public_key_crypto.py (elliptic curve math)
    - core/fundamentals/03_digital_signatures.py (signing concepts)

REAL-WORLD RELEVANCE:
    VRFs are used in Algorand for cryptographic sortition (selecting block
    proposers and committee members), in Chainlink for provably fair on-chain
    randomness (VRF v2), and in Cardano's Ouroboros Praos for leader selection.
"""

import hashlib
import os

# ============================================================================
# SECTION 1: CONSTANTS AND CONFIGURATION
# ============================================================================

# secp256k1 curve parameters (same as Bitcoin/Ethereum)
# Curve equation: y^2 = x^3 + 7 (mod P)
CURVE_P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
CURVE_A = 0
CURVE_B = 7

# Generator point G
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
G = (GX, GY)

# Group order — number of points generated by G
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141

# Identity element (point at infinity)
IDENTITY = None

# Display truncation
DISPLAY_LEN = 16

# ============================================================================
# SECTION 2: IMPLEMENTATION
# ============================================================================

# ----------------------------------------------------------------------------
# Elliptic curve primitives (self-contained, copied from 02_public_key_crypto)
# ----------------------------------------------------------------------------

def _mod_inv(a: int, m: int) -> int:
    """Modular inverse via Fermat's little theorem: a^(m-2) mod m."""
    return pow(a, m - 2, m)


def _point_add(p1: tuple | None, p2: tuple | None) -> tuple | None:
    """Add two points on secp256k1."""
    if p1 is IDENTITY:
        return p2
    if p2 is IDENTITY:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and y1 != y2:
        return IDENTITY
    if x1 == x2 and y1 == y2:
        return _point_double(p1)
    s = ((y2 - y1) * _mod_inv(x2 - x1, CURVE_P)) % CURVE_P
    x3 = (s * s - x1 - x2) % CURVE_P
    y3 = (s * (x1 - x3) - y1) % CURVE_P
    return (x3, y3)


def _point_double(p: tuple | None) -> tuple | None:
    """Double a point on secp256k1."""
    if p is IDENTITY:
        return IDENTITY
    x, y = p
    if y == 0:
        return IDENTITY
    s = ((3 * x * x + CURVE_A) * _mod_inv(2 * y, CURVE_P)) % CURVE_P
    x3 = (s * s - 2 * x) % CURVE_P
    y3 = (s * (x - x3) - y) % CURVE_P
    return (x3, y3)


def _scalar_mult(k: int, point: tuple | None) -> tuple | None:
    """Multiply point by scalar k using double-and-add."""
    if k == 0 or point is IDENTITY:
        return IDENTITY
    k = k % N
    result = IDENTITY
    addend = point
    while k > 0:
        if k & 1:
            result = _point_add(result, addend)
        addend = _point_double(addend)
        k >>= 1
    return result


def _point_to_bytes(point: tuple | None) -> bytes:
    """Serialize a point as compressed SEC format (33 bytes)."""
    if point is IDENTITY:
        return b"\x00"
    x, y = point
    # Prefix: 0x02 if y is even, 0x03 if y is odd
    prefix = b"\x02" if y % 2 == 0 else b"\x03"
    return prefix + x.to_bytes(32, "big")


def _hash_to_scalar(*parts: bytes) -> int:
    """Hash multiple byte strings to a scalar in [1, N-1].

    Used for deterministic nonce generation and challenge computation.
    We hash repeatedly if needed to get a value in range.
    """
    combined = b"".join(parts)
    h = hashlib.sha256(combined).digest()
    value = int.from_bytes(h, "big") % (N - 1) + 1  # Range [1, N-1]
    return value


# ----------------------------------------------------------------------------
# Hash-to-curve: map an arbitrary input to a point on secp256k1
# ----------------------------------------------------------------------------

def _hash_to_curve(data: bytes) -> tuple:
    """Map arbitrary data to a point on the secp256k1 curve.

    This is a simplified try-and-increment method:
    1. Hash the data to get an x-coordinate candidate
    2. Check if x^3 + 7 is a quadratic residue mod P
    3. If not, increment a counter and try again

    In production, use a constant-time method (like hash_to_curve from RFC 9380)
    to avoid timing side channels. For educational purposes, this is fine.
    """
    for counter in range(256):
        # Hash input with counter to get candidate x-coordinate
        h = hashlib.sha256(data + counter.to_bytes(4, "big")).digest()
        x = int.from_bytes(h, "big") % CURVE_P

        # Check if y^2 = x^3 + 7 has a solution (Euler's criterion)
        y_sq = (pow(x, 3, CURVE_P) + CURVE_B) % CURVE_P
        # y exists iff y_sq^((P-1)/2) = 1 mod P (quadratic residue test)
        if pow(y_sq, (CURVE_P - 1) // 2, CURVE_P) != 1:
            continue  # No valid y for this x, try next counter

        # Compute y using Tonelli-Shanks (for P = 3 mod 4, y = y_sq^((P+1)/4))
        # secp256k1's P satisfies P % 4 == 3, so this shortcut works
        y = pow(y_sq, (CURVE_P + 1) // 4, CURVE_P)

        # Always pick the even y for consistency
        if y % 2 != 0:
            y = CURVE_P - y

        return (x, y)

    # Extremely unlikely — would mean 256 consecutive failures
    raise ValueError("Failed to hash to curve (should be astronomically rare)")


# ----------------------------------------------------------------------------
# VRF: prove and verify
# ----------------------------------------------------------------------------

class VRF:
    """Elliptic Curve VRF (simplified ECVRF).

    The scheme works as follows:
    - prove(sk, input): compute gamma = sk * H(input), create DLEQ proof
    - verify(pk, input, output, proof): check the DLEQ proof

    The DLEQ (Discrete Log Equality) proof shows that:
        log_G(pk) == log_{H(input)}(gamma)
    i.e., the same secret key was used for both the public key and the VRF output.
    """

    @staticmethod
    def keygen() -> tuple[int, tuple]:
        """Generate a VRF keypair (secret key, public key).

        The secret key is a random scalar; the public key is sk * G.
        """
        sk = int.from_bytes(os.urandom(32), "big") % (N - 1) + 1
        pk = _scalar_mult(sk, G)
        return sk, pk

    @staticmethod
    def prove(sk: int, input_data: bytes) -> tuple[bytes, tuple, tuple, int, int]:
        """Produce a VRF output and proof for the given input.

        Args:
            sk: Secret key (scalar)
            input_data: Arbitrary input bytes

        Returns:
            (output, gamma, h_point, s, c) where:
            - output: 32-byte pseudorandom hash (the VRF output)
            - gamma: The VRF point (sk * H(input))
            - h_point: H(input) — the input hashed to a curve point
            - s, c: DLEQ proof components
        """
        # Step 1: Hash input to a curve point
        h_point = _hash_to_curve(input_data)

        # Step 2: Compute gamma = sk * H(input) — this is the core VRF computation
        # Gamma is deterministic given sk and input, making the output deterministic
        gamma = _scalar_mult(sk, h_point)

        # Step 3: Create a DLEQ proof (proves sk was used without revealing it)
        # Choose a random nonce k for the Schnorr-like proof
        k = _hash_to_scalar(
            sk.to_bytes(32, "big"),
            _point_to_bytes(h_point),
            input_data
        )  # Deterministic nonce (RFC 6979 style) to avoid nonce reuse attacks

        # Compute proof commitments: U = k*G, V = k*H
        u = _scalar_mult(k, G)          # Commitment with generator
        v = _scalar_mult(k, h_point)    # Commitment with hash point

        # Compute challenge c = hash(G, H, pk, gamma, U, V)
        pk = _scalar_mult(sk, G)
        c = _hash_to_scalar(
            _point_to_bytes(G),
            _point_to_bytes(h_point),
            _point_to_bytes(pk),
            _point_to_bytes(gamma),
            _point_to_bytes(u),
            _point_to_bytes(v),
        )

        # Compute response: s = k - c*sk mod N
        s = (k - c * sk) % N

        # Step 4: Derive the VRF output by hashing gamma
        # The output is a hash of gamma, making it uniformly distributed
        output = hashlib.sha256(b"VRF_OUTPUT:" + _point_to_bytes(gamma)).digest()

        return output, gamma, h_point, s, c

    @staticmethod
    def verify(pk: tuple, input_data: bytes, output: bytes,
               gamma: tuple, s: int, c: int) -> bool:
        """Verify a VRF proof.

        Checks the DLEQ proof: that gamma was computed with the same secret key
        that generated pk, without learning the secret key.

        Args:
            pk: Public key (point on curve)
            input_data: The input that was used
            output: The claimed VRF output (32 bytes)
            gamma: The VRF point from the proof
            s, c: DLEQ proof scalars

        Returns:
            True if the proof is valid, False otherwise.
        """
        # Step 1: Recompute H(input)
        h_point = _hash_to_curve(input_data)

        # Step 2: Recompute U = s*G + c*pk (should equal k*G from prover)
        # Because s = k - c*sk, we have: s*G + c*pk = (k - c*sk)*G + c*sk*G = k*G
        u_check = _point_add(
            _scalar_mult(s, G),
            _scalar_mult(c, pk)
        )

        # Step 3: Recompute V = s*H + c*gamma (should equal k*H from prover)
        # Because s = k - c*sk, we have: s*H + c*gamma = (k-c*sk)*H + c*sk*H = k*H
        v_check = _point_add(
            _scalar_mult(s, h_point),
            _scalar_mult(c, gamma)
        )

        # Step 4: Recompute challenge and compare
        c_check = _hash_to_scalar(
            _point_to_bytes(G),
            _point_to_bytes(h_point),
            _point_to_bytes(pk),
            _point_to_bytes(gamma),
            _point_to_bytes(u_check),
            _point_to_bytes(v_check),
        )

        if c_check != c:
            return False  # Challenge mismatch — proof is invalid

        # Step 5: Verify the output is derived from gamma correctly
        expected_output = hashlib.sha256(b"VRF_OUTPUT:" + _point_to_bytes(gamma)).digest()
        return output == expected_output


